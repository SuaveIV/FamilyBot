"""Shared pytest setup.

``familybot.config`` reads ``<repo>/config.yml`` at import time and calls ``sys.exit(1)``
when it is missing or fails validation. ``config.yml`` is gitignored because it holds the
Discord token and API keys, so a fresh clone and CI have none.

Write a throwaway config for the duration of the test session and delete it afterwards, so
the suite runs on a clean checkout without touching a developer's real config.
"""

import atexit
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = REPO_ROOT / "config.yml"

# Every value validate_config() insists on, filled with dummies. The steam ids are
# deliberately absent from user_id so that message formatting renders "Unknown User(...)";
# tests that care about name mapping patch FAMILY_USER_DICT themselves.
_MINIMAL_CONFIG = """\
# Generated by tests/conftest.py for this test session only; removed on exit.
discord:
  api_key: "test-discord-token"
  admin_id: 111111111111111111
free_epicgames:
  channel_id: 222222222222222222
steam_family:
  family_id: 123456
  channel_id:
    new_game: 333333333333333333
    wishlist: 444444444444444444
  user_id:
    "76561198000000099": "SomeoneElse"
  steamworks_api_key: "test-steamworks-key"
  itad_api_key: "test-itad-key"
  websocket_server_ip: "127.0.0.1"
help_message:
  channel_id: 555555555555555555
token_sender:
  token_save_path: "tokens"
  browser_profile_path: "FamilyBotBrowserProfile"
  update_buffer_hours: 24
web_ui:
  enabled: false
"""

_created_config = False

if not CONFIG_PATH.exists():
    CONFIG_PATH.write_text(_MINIMAL_CONFIG, encoding="utf-8")
    _created_config = True


@atexit.register
def _remove_generated_config() -> None:
    """Delete the generated config so the working tree is left as it was found."""
    if _created_config:
        CONFIG_PATH.unlink(missing_ok=True)
